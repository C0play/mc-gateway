from abc import ABC, abstractmethod

from ..utils.models import Container
from ..utils.keygen import KeyGenerator
from ..exceptions.errors import NotFoundError, ServiceError


class BaseContainerRepository(ABC):
    """A base class for managing container parameters stored in persistent storage"""
    
    @abstractmethod
    def __init__(self, key_generator: KeyGenerator) -> None:
        """
        Initializes the repository. Subdomains will be generated by `key_generator`.

        Args:
            key_generator: Class generating unique strings. 
        """
        self.key = key_generator
    

    @abstractmethod
    def create(self, ip: str, mc_port: int, rcon_port: int, rcon_password: str, config: dict) -> Container:
        """
        Creates a new container record.

        Args:
            ip: The IP address of the host running the container.
            mc_port: The Minecraft port exposed by the container.
            rcon_port: The RCON port exposed by the container.
            rcon_password: The RCON password for the container.
            config: Serialized ComposeConfig to persist for deferred deployment.

        Returns:
            Container: The newly created Container instance.

        Raises:
            ServiceError: If creation fails.
        """
        ...

    @abstractmethod
    def read(self, **filters) -> list[Container]:
        """
        Retrieves container records matching the given filters.

        Args:
            **filters: Field names and values to filter by (e.g. subdomain="abc",
                       to_be_deleted=True, host="1.2.3.4").

        Returns:
            list[Container]: Matching Container model instances.
        """
        ...
    
    @abstractmethod
    def update(self, subdomain: str, **fields) -> Container:
        """
        Updates arbitrary fields on a container record.

        Args:
            subdomain: The subdomain of the container.
            **fields: Field names and their new values.

        Returns:
            Container: The updated Container instance.

        Raises:
            NotFoundError: If the container does not exist.
        """
        ...

    @abstractmethod
    def delete(self, subdomain: str) -> None:
        """
        Removes the container with specified subdomain.

        Args:
            subdomain: The subdomain of the container to remove.
        
        Raises:
            NotFoundError: If the container does not exist.
        """
        ...



class SQLContainerRepository(BaseContainerRepository):
    """
    Implementation of storage using Peewee ORM.
    """

    def __init__(self, key_generator: KeyGenerator) -> None:
        query = Container.select(Container.subdomain)
        keys = [c.subdomain for c in query]
        key_generator.load(keys)
        super().__init__(key_generator)
        
         
    def create(self, ip: str, mc_port: int, rcon_port: int, rcon_password: str, config: dict) -> Container:
        try:
            new_key = self.key.gen()
            container = Container.create(
                subdomain=new_key,
                host=ip,
                mc_port=mc_port,
                rcon_port=rcon_port,
                rcon_password=rcon_password,
                config=config,
            )
            return container
        except Exception as e:
            raise ServiceError(f"failed to create container {ip}:{mc_port}: {e}")


    def read(self, **filters) -> list[Container]:
        query = Container.select()
        for field, value in filters.items():
            if value is None:
                continue
            query = query.where(getattr(Container, field) == value)
        return list(query)
    

    def update(self, subdomain: str, **fields) -> Container:
        rows = (Container
                    .update(**fields)
                    .where(Container.subdomain == subdomain)
                    .execute())
        if rows == 0:
            raise NotFoundError(f"container {subdomain} does not exist")
        return Container.get_by_id(subdomain)
    
    
    def delete(self, subdomain: str) -> None:
        query = (Container
                    .delete()
                    .where(Container.subdomain == subdomain))
        
        rows_deleted = query.execute()
        
        if rows_deleted == 0:
            raise NotFoundError(f"container {subdomain} does not exist")